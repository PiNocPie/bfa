// Throwaway test keys. Never fund these.
const AGENT_KEY: Hex = "0x59c6995e998f97a5a0044966f0945389dc9e86dae88c7a8412f4603b6b78690d";
const SELLER = "0x70997970C51812dc3A010C7d01b50e0d17dc79C8";
const USDC_BASE_SEPOLIA = "0x036CbD53842c5426634e7929541eC2318f3dCF7e";

function listing(price = "0.01"): Listing {
  return {
    manifest_version: 1,
    id: "demo/near-intents-status",
    provider: { name: "Nen demo seller", url: "https://example.com", contact: "ops@example.com" },
    name: "Demo endpoint",
    description: "Test endpoint used by the x402 client tests, on Base Sepolia.",
    categories: ["near-native"],
    endpoint: {
      url: "https://seller.test/status",
      method: "POST",
      input_schema: { type: "object" },
      output_schema: { type: "object", required: ["status"] },
      example_input: { deposit: "abc" },
    },
    pricing: { model: "per_call", amount_usd: price },
    payment: { protocol: "x402", networks: [NETWORKS.baseSepolia], payout: { via: "direct" } },
    data: { sources: "test", license_statement: "Test data generated by the test suite." },
  };
}

interface SellerOpts {
  askAtomic: string;
  body?: unknown;
}

/** A minimal x402 V2 seller: 402 + PAYMENT-REQUIRED, then verifies the EIP-3009 signature and settles. */
function fakeSeller(opts: SellerOpts) {
  const state = { calls: 0, verifiedPayers: [] as string[] };
  const impl: typeof fetch = async (input, init) => {
    state.calls++;
    const url = typeof input === "string" ? input : input instanceof URL ? input.toString() : input.url;
    const headers = new Headers(init?.headers ?? (input instanceof Request ? input.headers : undefined));
    const sigHeader = headers.get("PAYMENT-SIGNATURE");
    const requirements = {
      scheme: "exact",
      network: NETWORKS.baseSepolia,
      asset: USDC_BASE_SEPOLIA,
      amount: opts.askAtomic,
      payTo: SELLER,
      maxTimeoutSeconds: 60,
      extra: { name: "USDC", version: "2" },
    };
    if (!sigHeader) {
      const required = encodePaymentRequiredHeader({
        x402Version: 2,
        resource: { url, description: "demo", mimeType: "application/json" },
        accepts: [requirements],
      } as never);
      return new Response(JSON.stringify({}), { status: 402, headers: { "PAYMENT-REQUIRED": required } });
    }
    const payment = decodePaymentSignatureHeader(sigHeader) as unknown as {
      payload: { signature: Hex; authorization: { from: Hex; to: Hex; value: string; validAfter: string; validBefore: string; nonce: Hex } };
    };
    const a = payment.payload.authorization;
    const ok = await verifyTypedData({
      address: a.from,
      domain: { name: "USDC", version: "2", chainId: 84532, verifyingContract: USDC_BASE_SEPOLIA },
      types: {
        TransferWithAuthorization: [
          { name: "from", type: "address" },
          { name: "to", type: "address" },
          { name: "value", type: "uint256" },
          { name: "validAfter", type: "uint256" },
          { name: "validBefore", type: "uint256" },
          { name: "nonce", type: "bytes32" },
        ],
      },
      primaryType: "TransferWithAuthorization",
      message: { ...a, value: BigInt(a.value), validAfter: BigInt(a.validAfter), validBefore: BigInt(a.validBefore) },
      signature: payment.payload.signature,
    });
    if (!ok || getAddress(a.to) !== getAddress(SELLER) || a.value !== opts.askAtomic) {
      return new Response("bad payment", { status: 402 });
    }
    state.verifiedPayers.push(getAddress(a.from));
    const settle = encodePaymentResponseHeader({ success: true, transaction: "0xfeed", network: NETWORKS.baseSepolia, payer: a.from } as never);
    return new Response(JSON.stringify(opts.body ?? { status: "SUCCESS" }), {
      status: 200,
      headers: { "content-type": "application/json", "PAYMENT-RESPONSE": settle },
    });
  };
  return { impl, state };
}

async function newLog(): Promise<ReceiptLog> {
  return new ReceiptLog(join(await mkdtemp(join(tmpdir(), "nen-pay-")), "receipts.jsonl"));
}

describe("callListing over x402 V2", () => {
  it("pays the listed price and writes a paid_ok receipt with the settlement tx", async () => {
    const seller = fakeSeller({ askAtomic: "10000" }); // $0.01 in USDC atomic units
    const signer = localKeySigner(AGENT_KEY);
    const { receipt, data } = await callListing({ listing: listing(), input: { deposit: "abc" }, signer, log: await newLog(), fetchImpl: seller.impl });
    expect(receipt.status).toBe("paid_ok");
    expect(receipt.price_usd).toBe("0.01");
    expect(receipt.payment_tx).toBe("0xfeed");
    expect(receipt.output_valid).toBe(true);
    expect(data).toEqual({ status: "SUCCESS" });
    expect(seller.state.verifiedPayers).toEqual([signer.address]);
  });

  it("refuses to sign when the seller asks more than the listed price", async () => {
    const seller = fakeSeller({ askAtomic: "20000" }); // seller raised to $0.02 after review
    const { receipt } = await callListing({ listing: listing("0.01"), input: {}, signer: localKeySigner(AGENT_KEY), log: await newLog(), fetchImpl: seller.impl });
    expect(receipt.status).toBe("unpaid_error");
    expect(receipt.price_usd).toBe("0");
    expect(seller.state.verifiedPayers).toEqual([]);
  });

  it("marks paid calls that return nothing as paid_empty", async () => {
    const seller = fakeSeller({ askAtomic: "10000", body: { data: [] } });
    const { receipt } = await callListing({ listing: listing(), input: {}, signer: localKeySigner(AGENT_KEY), log: await newLog(), fetchImpl: seller.impl });
    expect(receipt.status).toBe("paid_empty");
    expect(receipt.output_valid).toBe(false);
  });

  it("never pays twice for the same idempotency key", async () => {
    const seller = fakeSeller({ askAtomic: "10000" });
    const log = await newLog();
    const args = { listing: listing(), input: {}, signer: localKeySigner(AGENT_KEY), log, fetchImpl: seller.impl, idempotencyKey: "task-42" };
    const first = await callListing(args);
    const second = await callListing(args);
    expect(second.replayed).toBe(true);
    expect(second.receipt.receipt_id).toBe(first.receipt.receipt_id);
    expect(seller.state.verifiedPayers).toHaveLength(1);
  });

  it("refuses before any request when the agent's max price is lower than the listing", async () => {
    const seller = fakeSeller({ askAtomic: "10000" });
    await expect(
      callListing({ listing: listing("0.01"), input: {}, signer: localKeySigner(AGENT_KEY), log: await newLog(), fetchImpl: seller.impl, maxPriceUsd: "0.005" }),
    ).rejects.toMatchObject({ code: "over_max_price" });
    expect(seller.state.calls).toBe(0);
  });
});

describe("Chain Signatures signer", () => {
  // Stand-in for NEAR's MPC network: same math (secp256k1 over the EIP-712 hash), returns r/s/recovery id like v1.signer.
  const mpcKey: Hex = "0x8b3a350cf5c34c9194ca85829a2df0ec3153be0318b5e2d3348e872092edffba";
  const fakeMpc: MpcBackend = {
    async deriveEvmAddress() {
      return privateKeyToAccount(mpcKey).address;
    },
    async signHash(_predecessor, _path, hash) {
      const sig = await sign({ hash, privateKey: mpcKey });
      return { r: sig.r, s: sig.s, v: Number(sig.yParity) };
    },
  };

  it("produces signatures a real x402 seller accepts", async () => {
    const signer = await chainSignaturesSigner({ mpc: fakeMpc, predecessor: "agent.testnet", path: "nen/agent-1" });
    expect(signer.kind).toBe("near-chain-signatures");
    const seller = fakeSeller({ askAtomic: "10000" });
    const { receipt } = await callListing({ listing: listing(), input: {}, signer, log: await newLog(), fetchImpl: seller.impl });
    expect(receipt.status).toBe("paid_ok");
    expect(seller.state.verifiedPayers).toEqual([privateKeyToAccount(mpcKey).address]);
  });

  it("normalizes recovery ids and rejects malformed components", () => {
    const r = "1".repeat(64);
    const s = "2".repeat(64);
    expect(rsvToHex({ r, s, v: 0 }).endsWith("1b")).toBe(true);
    expect(rsvToHex({ r: `0x${r}`, s, v: 28 }).endsWith("1c")).toBe(true);
    expect(() => rsvToHex({ r, s, v: 5 })).toThrow();
    expect(() => rsvToHex({ r: "zz", s, v: 0 })).toThrow();
  });
});
